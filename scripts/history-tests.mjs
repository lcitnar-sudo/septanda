/* Upgrade regression checks use synthetic history; they never connect to real player accounts. */
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {puzzles, engine, daily} from '../game.mjs';
import {createProgressTools} from '../backend/progress.mjs';
import {assertHistoryContract} from './history-contract.mjs';

const clone = value => JSON.parse(JSON.stringify(value));
const baseline = JSON.parse(await readFile(new URL('../content/published-history.json', import.meta.url), 'utf8'));
const calendar = JSON.parse(await readFile(new URL('../content/schedule.json', import.meta.url), 'utf8'));
const appSource = await readFile(new URL('../client/app.js', import.meta.url), 'utf8');
const input = {baseline, puzzles, calendar, appSource, daily, normalize: engine.normalize};
let checks = 0;
const check = (value, message) => {assert.ok(value, message); checks++;};
const equal = (value, expected, message) => {assert.deepEqual(value, expected, message); checks++;};
const rejects = (change, message) => {assert.throws(() => assertHistoryContract({...input, ...change}), message); checks++;};
assertHistoryContract(input); checks++;
rejects({puzzles: puzzles.slice(1)}, /nesmí zmizet/);
const renamed = clone(puzzles); renamed[0].id += '-new';
rejects({puzzles: renamed}, /nesmí zmizet/);
const replaced = clone(puzzles); replaced[0].answer = 'zcela jiný příběh'; replaced[0].variants = [];
rejects({puzzles: replaced}, /jiný výrok/);
const moved = clone(calendar); moved.days[0].ids.reverse();
rejects({calendar: moved}, /denní sada/);
rejects({calendar: {...calendar, startDate: '2026-10-20'}}, /kalendář/);
rejects({calendar: {...calendar, days: calendar.days.slice(0, -1)}}, /odebrané/);
rejects({appSource: appSource.replace('septanda.v6.daily', 'septanda.v7.daily')}, /guestStorageKey/);
rejects({daily: {...daily, createState: () => ({version: 7})}}, /stateVersion/);

const edited = clone(puzzles); edited[0].hint += ' Upřesnění.';
edited[0].variants.push(edited[0].answer); edited[0].answer = 'Opravené kanonické znění';
const corrected = assertHistoryContract({...input, puzzles: edited});
equal(corrected.puzzles[0], baseline.puzzles[0], 'editorial corrections retain the original identity even when recording later additions');
const additions = puzzles.slice(0, 5).map((puzzle, i) => ({...puzzle, id: 'future-new-' + i, answer: 'zcela nový archivní příběh ' + i, variants: []}));
const appended = {...input, puzzles: [...puzzles, ...additions], calendar: {...calendar, days: [...calendar.days, {ids: additions.map(puzzle => puzzle.id)}]}};
assert.throws(() => assertHistoryContract(appended), /content:record/); checks++;
const nextBaseline = assertHistoryContract({...appended, requireComplete: false});
equal(nextBaseline.puzzles.slice(0, baseline.puzzles.length), baseline.puzzles, 'new content is appended without rewriting old identities');
assertHistoryContract({...appended, baseline: nextBaseline}); checks++;

const date = '2026-10-16', ids = daily.plan(date), byId = new Map(puzzles.map(puzzle => [puzzle.id, puzzle]));
const fixture = daily.createState(null), day = daily.ensureDay(fixture, date);
day.progress[ids[0]] = {attempts: [{id: 'upgrade-attempt-1', text: byId.get(ids[0]).answer, time: 1}], hints: ['clue'], status: 'won', draft: ''};
day.progress[ids[1]] = {...daily.blankRound(), status: 'revealed'};
day.progress[ids[2]] = {...daily.blankRound(), draft: 'rozepsaný tip z dřívější verze'};
day.seen = ids.slice(0, 3); day.selected = ids[2];
const stored = createProgressTools({puzzles, engine, daily}).merge(null, fixture, {now: new Date('2026-10-16T12:00:00Z')});
equal(stored.stats.points, 250, 'published starting wallet, win award and purchased hint retain their value');
// Model a future stricter scorer: a previously awarded win must never revert to playing.
const stricter = {...engine, evaluate: (...args) => ({...engine.evaluate(...args), accepted: false})};
const newContext = vm.createContext({SeptandaEngine: stricter});
vm.runInContext(await readFile(new URL('../client/puzzles.js', import.meta.url), 'utf8'), newContext);
vm.runInContext(await readFile(new URL('../client/daily.js', import.meta.url), 'utf8'), newContext);
const updatedDaily = newContext.SeptandaDaily;
const restored = updatedDaily.sanitizeState(clone(stored.state));
check(restored.days[date].progress[ids[0]].status === 'won', 'client upgrade keeps an already won round');
check(restored.days[date].progress[ids[1]].status === 'revealed', 'client upgrade keeps a revealed round');
equal(clone(updatedDaily.totals(restored)), stored.stats, 'client upgrade preserves points, solved count, hints and attempt count');
equal(clone(restored.days[date].seen), day.seen, 'client upgrade retains shown-puzzle history');
check(restored.days[date].progress[ids[2]].draft === day.progress[ids[2]].draft, 'client upgrade keeps unfinished answers');
const nextDay = updatedDaily.ensureDay(restored, '2026-10-18');
check(nextDay.skipped.includes(ids[0]) && nextDay.skipped.includes(ids[1]), 'upgrade still skips known statements on later days');
const updatedServer = createProgressTools({puzzles, engine: stricter, daily: updatedDaily});
const merged = updatedServer.merge(stored.state, daily.createState(null), {now: new Date('2026-10-18T12:00:00Z')});
equal(merged.stats, stored.stats, 'an empty or stale device after deployment cannot erase awarded points or history');
equal(merged.scores, stored.scores, 'an updated scorer does not remove past leaderboard results');
equal(merged.state.days[date].seen, stored.state.days[date].seen, 'server keeps exposure records missing from a stale client');
equal(merged.state.days[date].progress[ids[2]].draft, day.progress[ids[2]].draft, 'server keeps draft when incoming device has no day');
const forged = clone(fixture); forged.days[date].progress = {[ids[0]]: {...day.progress[ids[0]], attempts: [{text: 'podvržená výhra', time: 1}]}};
check(updatedServer.merge(null, forged, {now: new Date('2026-10-16T12:00:00Z')}).stats.points === 50, 'client won flag still cannot create a new server award');
console.log(JSON.stringify({historyUpgradeChecks: checks, protectedPuzzles: baseline.puzzles.length, protectedDailySets: baseline.calendar.days.length}));
